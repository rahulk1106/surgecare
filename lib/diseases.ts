export function getAllDiseases(): Disease[] {
  return categories.flatMap(c => c.diseases)
}

export function getDiseaseBySlug(slug: string): Disease | undefined {
  return getAllDiseases().find(d => d.slug === slug)
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return categories.find(c => c.slug === slug)
}

export function getDiseasesByCategory(categorySlug: string): Disease[] {
  return getAllDiseases().filter(d => d.categorySlug === categorySlug)
}

export function getRelatedDiseases(slugs: string[]): Disease[] {
  return getAllDiseases().filter(d => slugs.includes(d.slug))
}

